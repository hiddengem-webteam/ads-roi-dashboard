// Collects video/specs/*.json into video/src/flohom/specs.generated.ts so Root.tsx can
// register one Remotion composition per client spec (the bundler has no glob import).
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'video', 'specs');
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort() : [];
const specs = files.map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
const out = `// Generated by scripts/build-reel-specs.mjs from video/specs/*.json. Do not edit.\nimport type { ReelSpec } from "./ClientReel";\nexport const SPECS: ReelSpec[] = ${JSON.stringify(specs, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'video', 'src', 'flohom', 'specs.generated.ts'), out);
console.log(`${specs.length} spec(s): ${specs.map((s) => s.slug).join(', ') || 'none'}`);
